"""
verdict.py
----------
Combines the individual checks into one risk level for the UI / API.

Signals are treated as independent evidence: ``score = 1 - prod(1 - s_i)``.
ELA is deliberately NOT part of the verdict: on real camera photos it gave
false alarms on 6/28 clean copies and located 0/84 edits
(see README "Real-world results"). It is shown as a visual aid only.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from src.forensics.dtd import DtdReport
    from src.forensics.trufor import TruForReport

HIGH = 0.7
MEDIUM = 0.4
DUPLICATE_WEIGHT = 0.5
TRUFOR_SUSPICIOUS_WEIGHT = 0.85
TRUFOR_SCORE_WEIGHT = 0.5  # unflagged TruFor score adds a little evidence
DTD_SUSPICIOUS_WEIGHT = 0.85


@dataclass(frozen=True)
class Verdict:
    level: str  # low | medium | high
    score: float
    reasons: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


def combine(metadata_risk: float, duplicate: bool, trufor: TruForReport | None,
            dtd: DtdReport | None = None) -> Verdict:
    signals: list[tuple[float, str]] = []
    if metadata_risk > 0:
        signals.append((metadata_risk, _metadata_reason(metadata_risk)))
    if duplicate:
        signals.append((DUPLICATE_WEIGHT, "Very similar to a photo submitted before"))
    if trufor is not None:
        if trufor.suspicious:
            signals.append((max(TRUFOR_SUSPICIOUS_WEIGHT, trufor.score),
                            "Forgery detector marks a manipulated area"))
        elif trufor.score > 0:
            signals.append((trufor.score * TRUFOR_SCORE_WEIGHT, ""))
    if dtd is not None and dtd.suspicious:
        signals.append((DTD_SUSPICIOUS_WEIGHT, "Document scan finds edited text"))

    clean = 1.0
    for s, _ in signals:
        clean *= 1.0 - s
    score = round(1.0 - clean, 3)
    level = "high" if score >= HIGH else "medium" if score >= MEDIUM else "low"
    reasons = [r for s, r in sorted(signals, reverse=True) if r]
    return Verdict(level, score, reasons)


def _metadata_reason(risk: float) -> str:
    if risk >= 0.9:
        return "Metadata says the image was generated by AI"
    if risk >= 0.5:
        return "Metadata shows editing software"
    return "Metadata is incomplete (often stripped by apps)"
